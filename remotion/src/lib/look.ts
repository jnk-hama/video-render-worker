/**
 * 背景の実写素材に掛ける色補正（2026-09-09・決定#114）。
 *
 * ★オーナー指示「ナレーションや動画もなるべく派手に購買意欲を高めること」。
 *
 * 【実測して決めた（推測で書かない）】
 * 本番フレームを背景にして、掛ける／掛けないの2通りを描いて測った。
 * 画面下半分（映像が見えている所）の平均彩度・平均輝度・明暗差:
 *
 *   掛けない                     彩度 0.1532 / 輝度 35.31 / 明暗差 30.66
 *   saturate(1.28)               彩度 0.1574 (+2.7%) / 輝度 変化なし
 *   saturate(1.28) contrast(1.1) 彩度 0.1505 (**−1.8%**) / 輝度 33.14 (−6.1%)
 *
 * ★**contrast は入れない。** 目的は色を出すことなのに、測ると彩度が
 *   下がって暗くなった。この後さらに黒の膜を重ねるので、明暗差を上げると
 *   暗部が先に潰れる。「派手にする」つもりで逆へ動く。
 *
 * ★彩度の効きは +2.7% と小さいが、これは**測った素材が既に暗い**ため
 *   （本番の完成動画を背景に使ったので二重に暗い）。実際の経路では
 *   この補正は**黒の膜を重ねる前**の生のストック映像に掛かるので、
 *   効きはこれより大きいはずである。★ただしそこは未実測。
 *
 * ★1.28 で止める理由：これ以上は肌がオレンジに転ぶ。人物素材が多い。
 *   UGC風に見せる前提なので「効いているが加工とは気づかれない」範囲に留める。
 *
 * ★描画時間はほぼ増えない（GPUの1パス。モーションブラーのように
 *   フレームを何度も描き直すわけではない）。無料枠を守る前提を崩さない。
 */
